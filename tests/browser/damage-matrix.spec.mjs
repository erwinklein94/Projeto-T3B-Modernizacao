import { test, expect } from "@playwright/test";
import { fixture, filePayload } from "../workbook-fixture.mjs";

test("Danificados apresenta matriz por origem e data, totais e lacunas sem duplicar o Excel", async ({ page }) => {
  const title = "Controle Dormentes Volume Espécies Jales";
  const workbook = fixture();
  const sheet = workbook.addWorksheet("Danif.");
  sheet.addRow(["DANIFICADOS", ...[1, 8, 15, 22].map((day) => new Date(`2026-06-${String(day).padStart(2, "0")}T00:00:00Z`))]);
  sheet.addRow(["Fornecedor A", 3, 4, 5]);
  sheet.addRow(["Fornecedor B", 2, 3, 5]);
  sheet.addRow(["Base da esteira", 1, null, 2]);
  sheet.addRow(["TOTAL", 6, 7, 12]);
  await page.goto("./");
  await page.getByRole("button", { name: "Inserir dados", exact: true }).click();
  await page.getByLabel(title, { exact: true }).and(page.locator("input[type=file]")).setInputFiles(await filePayload(workbook));
  await expect(page.getByText("Planilha: controle.xlsx", { exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Fechar aviso", exact: true }).click();
  await page.locator("nav").getByRole("button", { name: title, exact: true }).click();
  const panel = page.locator(".damage-panel"), matrix = panel.locator(".damage-matrix");
  await expect(matrix.locator("tbody tr")).toHaveCount(3);
  await expect(matrix.getByRole("columnheader", { name: "22/06/2026", exact: true })).toBeVisible();
  await expect(matrix.locator("tfoot td")).toHaveText(["6", "7 *", "12", "—"]);
  await expect(matrix.getByRole("rowheader", { name: "Base da esteira", exact: true })).toBeVisible();
  await panel.getByText("Consultar ocorrências detalhadas de danificados", { exact: true }).click();
  await expect(panel.getByText("Nenhuma ocorrência neste filtro.", { exact: true })).toBeVisible();
  const filters = page.getByRole("region", { name: "Filtros do dashboard", exact: true });
  await filters.scrollIntoViewIfNeeded();
  await filters.getByRole("combobox", { name: "Fornecedor", exact: true }).selectOption("Fornecedor A");
  await filters.getByLabel("Data inicial", { exact: true }).fill("2026-06-08");
  await expect(matrix.locator("tbody tr")).toHaveCount(1);
  await expect(matrix.locator("tfoot td")).toHaveText(["4", "5", "—"]);
  await filters.getByLabel("Espécie", { exact: true }).selectOption("Espécie A");
  await expect(matrix.locator("tfoot td")).toHaveText(["4", "5", "—"]);
  await filters.getByLabel("Data inicial", { exact: true }).fill("2027-01-01");
  await expect(panel.getByText("Nenhuma apuração encontrada para o fornecedor ou período selecionado.", { exact: true })).toBeVisible();
  await filters.getByRole("button", { name: "Limpar", exact: true }).click();
  await page.getByRole("button", { name: "Ativar tema escuro", exact: true }).click();
  await expect(matrix.locator("tbody tr")).toHaveCount(3);
  const download = page.waitForEvent("download");
  await page.getByRole("button", { name: "Exportar PDF", exact: true }).click();
  expect((await download).suggestedFilename()).toBe("T3B-dashboard.pdf");
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
});
